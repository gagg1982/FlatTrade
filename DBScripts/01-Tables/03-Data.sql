TRUNCATE TABLE ExcludedStockInstruments;
insert into ExcludedStockInstruments (token, TradingSymbol, Exchange)
select token, TradingSymbol, ExchangeCode 
from StockInstruments si 
where isin not like 'INE%'
and active=1 
and Not EXISTS (Select 1 from ExcludedStockInstruments esi where esi.Token = si.token and esi.Exchange = si.ExchangeCode)
